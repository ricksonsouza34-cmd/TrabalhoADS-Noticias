create table if not exists public.news (
  id bigint generated by default as identity primary key,
  title text not null,
  category text not null check (category in ('Brasil','Mundo','Tecnologia','Esportes')),
  content text not null,
  image text,
  author_id uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);
alter table public.news enable row level security;
drop policy if exists "Noticias publicas para leitura" on public.news;
create policy "Noticias publicas para leitura" on public.news for select using (true);
drop policy if exists "Usuario pode inserir propria noticia" on public.news;
create policy "Usuario pode inserir propria noticia" on public.news for insert to authenticated with check (auth.uid()=author_id);
drop policy if exists "Usuario pode alterar propria noticia" on public.news;
create policy "Usuario pode alterar propria noticia" on public.news for update to authenticated using (auth.uid()=author_id) with check (auth.uid()=author_id);
drop policy if exists "Usuario pode excluir propria noticia" on public.news;
create policy "Usuario pode excluir propria noticia" on public.news for delete to authenticated using (auth.uid()=author_id);
